const WUXIA_TONE_LEVELS = [20, 50, 80];

function normalizeWuxiaTone(tone) {
  const n = Number(tone);
  if (!Number.isFinite(n)) return WUXIA_TONE_LEVELS[0];
  return WUXIA_TONE_LEVELS.reduce(
    (best, level) => (Math.abs(level - n) < Math.abs(best - n) ? level : best),
    WUXIA_TONE_LEVELS[0]
  );
}

